    @staticmethod
    def _rules(rules: str) -> dict[str, str]:
        result = {}
        for raw in rules.splitlines():
            line = raw.strip()
            if line:
                phrase, sep, label = line.partition("=>")
                result[phrase.strip()] = normalize_label(
                    (label if sep else "СЛОВАРЬ").strip("[] ")
                )
        return result

