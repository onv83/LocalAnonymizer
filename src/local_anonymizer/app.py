def asset_path(name: str) -> Path:
    base = Path(getattr(sys, "_MEIPASS", Path(__file__).resolve().parent))
    candidate = base / "assets" / name
    if not candidate.exists():
        candidate = Path(__file__).resolve().parent / "assets" / name
    return candidate


