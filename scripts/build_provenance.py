from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts import verify_packaged


_REVISION_RE = re.compile(r"[0-9a-f]{40,64}")
_DIGEST_RE = re.compile(r"[0-9a-f]{64}")


def write_provenance_module(
    destination: str | Path,
    *,
    source_root: str | Path = ROOT,
    git_revision: str | None = None,
    git_diff_sha256: str | None = None,
) -> dict[str, str]:
    root = Path(source_root).resolve()
    revision = git_revision or verify_packaged.git_revision(root)
    diff_hash = git_diff_sha256 or verify_packaged.git_diff_sha256(root)
    if _REVISION_RE.fullmatch(revision) is None:
        raise verify_packaged.VerificationError("Git revision has an invalid format")
    if _DIGEST_RE.fullmatch(diff_hash) is None:
        raise verify_packaged.VerificationError("Git diff hash has an invalid format")
    payload = {
        "source_snapshot_sha256": verify_packaged.source_snapshot_sha256(root),
        "git_revision": revision,
        "git_diff_sha256": diff_hash,
    }
    path = Path(destination)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(
        "# Generated by scripts/build_provenance.py; do not edit or commit.\n"
        f'SOURCE_SNAPSHOT_SHA256 = "{payload["source_snapshot_sha256"]}"\n'
        f'GIT_REVISION = "{payload["git_revision"]}"\n'
        f'GIT_DIFF_SHA256 = "{payload["git_diff_sha256"]}"\n',
        encoding="utf-8",
    )
    temporary.replace(path)
    return payload


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate immutable build provenance for the packaged executable"
    )
    parser.add_argument("destination")
    args = parser.parse_args(argv)
    try:
        payload = write_provenance_module(args.destination)
    except verify_packaged.VerificationError as exc:
        print(f"Build provenance failed: {exc}", file=sys.stderr)
        return 1
    print(json.dumps(payload, ensure_ascii=False, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
